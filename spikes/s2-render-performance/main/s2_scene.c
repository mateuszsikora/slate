static lv_obj_t *s2_icon_label(lv_obj_t *parent, const char *glyph, bool large, uint32_t colour)
{
    lv_obj_t *icon = lv_label_create(parent);
    lv_label_set_text(icon, glyph);
    lv_obj_set_style_text_font(icon, large ? &slate_font_icons_48 : &slate_font_icons_28,
                               LV_PART_MAIN);
    lv_obj_set_style_text_color(icon, lv_color_hex(colour), LV_PART_MAIN);
    return icon;
}

/* §7.5: a name that does not fit is marquee-scrolled, never clipped. The
 * scrolling label is also a per-frame invalidation, which is a render cost that
 * a static label would not have and that a real dashboard will have. */
static lv_obj_t *s2_name_label(lv_obj_t *parent, const char *text, int32_t width)
{
    lv_obj_t *label = lv_label_create(parent);
    lv_label_set_text(label, text);
    lv_label_set_long_mode(label, LV_LABEL_LONG_MODE_SCROLL_CIRCULAR);
    lv_obj_set_width(label, width);
    lv_obj_set_style_text_font(label, &slate_font_caption_15, LV_PART_MAIN);
    lv_obj_set_style_text_color(label, lv_color_hex(S2_COL_TEXT_LO), LV_PART_MAIN);
    return label;
}

static void s2_build_light(s2_tile_t *t, int32_t w, int32_t h, const s2_recipe_t *r, bool animated)
{
    t->icon = s2_icon_label(t->tile, r->icon, r->w >= 2 && r->h >= 2, S2_COL_WARN);
    lv_obj_align(t->icon, LV_ALIGN_TOP_LEFT, 0, 0);

    lv_obj_t *name = s2_name_label(t->tile, r->label, w - 2 * S2_MARGIN);
    lv_obj_align(name, LV_ALIGN_BOTTOM_LEFT, 0, 0);

    /* §7.1: 2×1 and larger carry a brightness percentage and a slider. */
    if (r->w >= 2) {
        t->value = lv_label_create(t->tile);
        lv_label_set_text(t->value, "62%");
        lv_obj_set_style_text_font(t->value, &slate_font_body_20, LV_PART_MAIN);
        lv_obj_set_style_text_color(t->value, lv_color_hex(S2_COL_TEXT_HI), LV_PART_MAIN);
        lv_obj_align(t->value, LV_ALIGN_TOP_RIGHT, 0, 0);

        t->slider = lv_slider_create(t->tile);
        lv_obj_set_size(t->slider, w - 2 * S2_MARGIN, 12);
        lv_obj_align(t->slider, LV_ALIGN_CENTER, 0, h / 8);
        lv_slider_set_value(t->slider, 62, LV_ANIM_OFF);
        lv_obj_set_style_bg_color(t->slider, lv_color_hex(S2_COL_SURFACE_ALT), LV_PART_MAIN);
        lv_obj_set_style_bg_color(t->slider, lv_color_hex(S2_COL_ACCENT), LV_PART_INDICATOR);
    }

    /* §7.5: every action shows a pending state. */
    if (animated) {
        s2_start_pulse(t->icon, 700);
    }
}

static void s2_build_cover(s2_tile_t *t, int32_t w, int32_t h, const s2_recipe_t *r, bool animated)
{
    t->icon = s2_icon_label(t->tile, r->icon, false, S2_COL_TEXT_HI);
    lv_obj_align(t->icon, LV_ALIGN_TOP_LEFT, 0, 0);

    lv_obj_t *name = s2_name_label(t->tile, r->label, w - 2 * S2_MARGIN);
    lv_obj_align(name, LV_ALIGN_BOTTOM_LEFT, 0, 0);

    /* §7.2: up / stop / down, §7.5: touch targets ≥ 48 px. */
    static const char *glyphs[] = { S2_ICON_ARROW_UP, S2_ICON_STOP, S2_ICON_ARROW_DOWN };
    const bool vertical = r->h >= 2;
    for (int i = 0; i < 3; i++) {
        lv_obj_t *btn = lv_button_create(t->tile);
        lv_obj_set_size(btn, 48, 48);
        lv_obj_align(btn, vertical ? LV_ALIGN_TOP_MID : LV_ALIGN_LEFT_MID,
                     vertical ? 0 : (int32_t)i * 52,
                     vertical ? 30 + (int32_t)i * 52 : 0);
        lv_obj_set_style_bg_color(btn, lv_color_hex(S2_COL_SURFACE_ALT), LV_PART_MAIN);
        lv_obj_set_style_radius(btn, S2_RADIUS / 2, LV_PART_MAIN);
        lv_obj_t *sym = lv_label_create(btn);
        lv_label_set_text(sym, glyphs[i]);
        lv_obj_set_style_text_font(sym, &slate_font_icons_28, LV_PART_MAIN);
        lv_obj_center(sym);
    }

    /* §7.2: movement shows an animated indicator until the state settles. */
    t->bar = lv_bar_create(t->tile);
    lv_obj_set_size(t->bar, w - 2 * S2_MARGIN, 6);
    lv_obj_align(t->bar, LV_ALIGN_BOTTOM_MID, 0, -18);
    lv_bar_set_range(t->bar, 0, 100);
    lv_bar_set_value(t->bar, 40, LV_ANIM_OFF);
    lv_obj_set_style_bg_color(t->bar, lv_color_hex(S2_COL_SURFACE_ALT), LV_PART_MAIN);
    lv_obj_set_style_bg_color(t->bar, lv_color_hex(S2_COL_ACCENT), LV_PART_INDICATOR);
    if (animated) {
        s2_start_travel(t->bar);
    }
    (void)h;
}

static void s2_build_sensor(s2_tile_t *t, int32_t w, const s2_recipe_t *r)
{
    t->value = lv_label_create(t->tile);
    lv_label_set_text(t->value, "21.4");
    /* §8: hero 44 for the value. §7.5 out-of-range: a longer string steps the
     * type scale down rather than overflowing — s2_scene_update() exercises both
     * branches, and they cost different amounts of glyph work. */
    lv_obj_set_style_text_font(t->value, &slate_font_hero_44, LV_PART_MAIN);
    lv_obj_set_style_text_color(t->value, lv_color_hex(S2_COL_TEXT_HI), LV_PART_MAIN);
    lv_obj_align(t->value, LV_ALIGN_LEFT_MID, 0, -6);

    if (r->w >= 2) {
        t->icon = s2_icon_label(t->tile, r->icon, false, S2_COL_TEXT_LO);
        lv_obj_align(t->icon, LV_ALIGN_TOP_RIGHT, 0, 0);
    }

    lv_obj_t *name = s2_name_label(t->tile, r->label, w - 2 * S2_MARGIN);
    lv_obj_align(name, LV_ALIGN_BOTTOM_LEFT, 0, 0);
    t->unit = "°C";
}

static void s2_build_scene(s2_tile_t *t, int32_t w, const s2_recipe_t *r)
{
    t->icon = s2_icon_label(t->tile, r->icon, false, S2_COL_ACCENT);
    lv_obj_align(t->icon, LV_ALIGN_CENTER, 0, -12);

    lv_obj_t *name = s2_name_label(t->tile, r->label, w - 2 * S2_MARGIN);
    lv_obj_align(name, LV_ALIGN_BOTTOM_MID, 0, 0);
}

