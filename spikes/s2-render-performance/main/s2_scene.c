/* -------------------------------------------------------------------------
 * Page build and destroy — the §6.4 PUT /config path
 * ------------------------------------------------------------------------- */

lv_obj_t *s2_scene_build(uint32_t index)
{
    memset(s_tiles, 0, sizeof(s_tiles));
    s_tile_count = 0;

    lv_obj_t *screen = lv_screen_active();
    lv_obj_set_style_bg_color(screen, lv_color_hex(S2_COL_BG), LV_PART_MAIN);

    lv_obj_t *root = lv_obj_create(screen);
    lv_obj_set_size(root, S2_SCREEN_W, S2_SCREEN_H);
    lv_obj_set_pos(root, 0, 0);
    lv_obj_set_style_bg_color(root, lv_color_hex(S2_COL_BG), LV_PART_MAIN);
    lv_obj_set_style_border_width(root, 0, LV_PART_MAIN);
    lv_obj_set_style_pad_all(root, 0, LV_PART_MAIN);
    lv_obj_remove_flag(root, LV_OBJ_FLAG_SCROLLABLE);

    /* §3.2: the 56 px system bar is fixed and not configurable. It carries the
     * clock, which changes every second in the real firmware and is therefore
     * part of the steady-state render cost. */
    lv_obj_t *bar = lv_obj_create(root);
    lv_obj_set_size(bar, S2_SCREEN_W, S2_BAR_H);
    lv_obj_set_pos(bar, 0, 0);
    lv_obj_set_style_bg_color(bar, lv_color_hex(S2_COL_SURFACE), LV_PART_MAIN);
    lv_obj_set_style_border_width(bar, 0, LV_PART_MAIN);
    lv_obj_set_style_radius(bar, 0, LV_PART_MAIN);
    lv_obj_remove_flag(bar, LV_OBJ_FLAG_SCROLLABLE);

    lv_obj_t *clock = lv_label_create(bar);
    lv_label_set_text(clock, "22:41");
    lv_obj_set_style_text_font(clock, &slate_font_body_20, LV_PART_MAIN);
    lv_obj_set_style_text_color(clock, lv_color_hex(S2_COL_TEXT_HI), LV_PART_MAIN);
    lv_obj_align(clock, LV_ALIGN_LEFT_MID, 0, 0);

    lv_obj_t *title = lv_label_create(bar);
    lv_label_set_text_fmt(title, "Page %u", (unsigned)(index + 1));
    lv_obj_set_style_text_font(title, &slate_font_body_20, LV_PART_MAIN);
    lv_obj_set_style_text_color(title, lv_color_hex(S2_COL_TEXT_HI), LV_PART_MAIN);
    lv_obj_center(title);

    lv_obj_t *wifi = s2_icon_label(bar, S2_ICON_WIFI_STRENGTH_4, false, S2_COL_TEXT_LO);
    lv_obj_align(wifi, LV_ALIGN_RIGHT_MID, 0, 0);

    /*
     * Build tag. Not decoration: this spike's pass criterion is what a person
     * sees, and visual judgements were twice nearly recorded against the wrong
     * build because the panel had been reflashed between the question and the
     * answer. The tag makes "which one am I looking at" answerable from the
     * panel itself rather than from the order of events in a chat.
     *
     * It hangs off the root rather than off the system bar. Putting a fourth
     * child in the bar disturbed the bar's own layout — the page title stopped
     * sitting where it belongs — and an instrument that changes the thing it is
     * measuring is worse than no instrument. Here it overlaps nothing: the §3.2
     * grid ends 14 px above the bottom edge and this sits in that margin.
     */
    lv_obj_t *tag = lv_label_create(root);
    lv_label_set_text(tag, S2_BUILD_TAG);
    lv_obj_set_style_text_font(tag, &slate_font_caption_15, LV_PART_MAIN);
    lv_obj_set_style_text_color(tag, lv_color_hex(S2_COL_ACCENT), LV_PART_MAIN);
    lv_obj_align(tag, LV_ALIGN_BOTTOM_RIGHT, -2, 0);

    /*
     * Tiles are laid out cell by cell, and the page always ends up with exactly
     * S2_TILES tiles — the count is the variable under test, so a multi-cell
     * tile eating a neighbour's cell would quietly measure a smaller page than
     * the one being reported.
     *
     * The rule: a recipe gets its §3.2 size only while the grid can still spare
     * the cells; from the moment the tiles left to place equal the cells left
     * free, everything is 1×1. Saturating a 4 × 3 grid with twelve tiles
     * therefore means twelve 1×1 tiles, which is not a simplification but what
     * §3.2 forces — twelve is only reachable at the smallest size. Lower counts
     * leave room and produce the mixed pages the size variants in §7 describe.
     */
    bool occupied[S2_GRID_ROWS][S2_GRID_COLS];
    memset(occupied, 0, sizeof(occupied));
    uint32_t free_cells = S2_GRID_ROWS * S2_GRID_COLS;

    /* §13 asks for four animated tiles; the selection is inside the loop. */
    uint32_t animated_so_far = 0;

    for (uint32_t i = 0; i < S2_TILES; i++) {
        const s2_recipe_t *r = &S2_RECIPES[(i + index * 3) % S2_RECIPE_COUNT];

        int col = -1, row = -1;
        uint8_t tw = 1, th = 1;
        for (int rr = 0; rr < S2_GRID_ROWS && row < 0; rr++) {
            for (int cc = 0; cc < S2_GRID_COLS && row < 0; cc++) {
                if (occupied[rr][cc]) {
                    continue;
                }
                col = cc;
                row = rr;

                const uint32_t tiles_left = S2_TILES - i;
                if (free_cells <= tiles_left) {
                    break; /* every remaining tile needs a cell of its own */
                }
                bool fits = (cc + r->w <= S2_GRID_COLS) && (rr + r->h <= S2_GRID_ROWS) &&
                            (free_cells - (uint32_t)(r->w * r->h) >= tiles_left - 1);
                for (int y = rr; fits && y < rr + r->h; y++) {
                    for (int x = cc; fits && x < cc + r->w; x++) {
                        fits = !occupied[y][x];
                    }
                }
                if (fits) {
                    tw = r->w;
                    th = r->h;
                }
            }
        }
        if (row < 0) {
            break; /* grid full — only possible if S2_TILES exceeds the cells */
        }
        free_cells -= (uint32_t)(tw * th);
        for (int y = row; y < row + th; y++) {
            for (int x = col; x < col + tw; x++) {
                occupied[y][x] = true;
            }
        }

        const int32_t w = tw * S2_CELL_W + (tw - 1) * S2_GAP;
        const int32_t h = th * S2_CELL_H + (th - 1) * S2_GAP;
        const int32_t x = S2_MARGIN + col * (S2_CELL_W + S2_GAP);
        const int32_t y = S2_BAR_H + S2_MARGIN + row * (S2_CELL_H + S2_GAP);

        s2_tile_t *t = &s_tiles[s_tile_count];
        t->type = r->type;
        t->tile = lv_obj_create(root);
        lv_obj_set_size(t->tile, w, h);
        lv_obj_set_pos(t->tile, x, y);
        lv_obj_set_style_bg_color(t->tile, lv_color_hex(S2_COL_SURFACE), LV_PART_MAIN);
        lv_obj_set_style_radius(t->tile, S2_RADIUS, LV_PART_MAIN);
        lv_obj_set_style_border_width(t->tile, 0, LV_PART_MAIN);
        lv_obj_set_style_pad_all(t->tile, S2_MARGIN, LV_PART_MAIN);
        lv_obj_remove_flag(t->tile, LV_OBJ_FLAG_SCROLLABLE);

        /*
         * The issue asks for four animated tiles, and getting this wrong
         * under-loads the whole measurement.
         *
         * The first version picked every fifth tile — indices 0, 5, 10, 15 —
         * without noticing that only light and cover have an animated variant
         * (§7.1 pending pulse, §7.2 movement indicator); sensor and scene
         * ignore the flag. On the twelve-tile page those indices land on one
         * light and three tiles that cannot animate, so the scene ran with
         * **one** animation instead of four and every frame-time number was
         * measured against a lighter load than §13 specifies.
         *
         * Counting only the tiles that can actually animate fixes it. The
         * symptom that exposed it was rendering *gaps*: with almost nothing
         * moving, LVGL correctly drew nothing for 100-300 ms at a time, which
         * a frame-time percentile cannot show because a frame that was never
         * rendered is not in the sample.
         */
        const bool animated = (r->type == S2_LIGHT || r->type == S2_COVER) &&
                              animated_so_far < S2_ANIMATED_TILES;
        if (animated) {
            animated_so_far++;
        }

        s2_recipe_t sized = *r;
        sized.w = tw;
        sized.h = th;

        switch (r->type) {
        case S2_LIGHT:   s2_build_light(t, w, h, &sized, animated); break;
        case S2_COVER:   s2_build_cover(t, w, h, &sized, animated); break;
        case S2_SENSOR:  s2_build_sensor(t, w, &sized); break;
        case S2_SCENE:   s2_build_scene(t, w, &sized); break;
        default:         s2_build_unknown(t, &sized); break;
        }
        s_tile_count++;
    }

    return root;
}

void s2_scene_destroy(lv_obj_t *root)
{
    /* Deleting a tree with animations still attached is the case §6.4 has to
     * survive and the one S-1 measured for leaks; here it is simply the switch
     * path being timed. */
    lv_obj_delete(root);
    memset(s_tiles, 0, sizeof(s_tiles));
    s_tile_count = 0;
}

/* -------------------------------------------------------------------------
 * Entity updates (§5.2) — 10 per second
 * ------------------------------------------------------------------------- */

void s2_scene_update(uint32_t seq)
{
    if (s_tile_count == 0) {
        return;
    }
    s2_tile_t *t = &s_tiles[seq % s_tile_count];

    switch (t->type) {
    case S2_SENSOR:
        if (t->value) {
            /*
             * §7.5 out-of-range: every tenth update is a four-digit reading, so
             * the type scale steps down and the label re-lays out at a different
             * size. That is a heavier update than changing a digit, and a real
             * dashboard with a pressure sensor has one on screen permanently.
             */
            char buf[16];
            if ((seq % 10) == 0) {
                snprintf(buf, sizeof(buf), "1013.%u", (unsigned)(seq % 10));
                lv_obj_set_style_text_font(t->value, &slate_font_body_20, LV_PART_MAIN);
            } else {
                snprintf(buf, sizeof(buf), "%u.%u", (unsigned)(18 + seq % 9),
                         (unsigned)(seq % 10));
                lv_obj_set_style_text_font(t->value, &slate_font_hero_44, LV_PART_MAIN);
            }
            lv_label_set_text(t->value, buf);
        }
        break;

    case S2_LIGHT:
        if (t->slider) {
            const int32_t pct = (int32_t)(seq * 7 % 101);
            lv_slider_set_value(t->slider, pct, LV_ANIM_OFF);
            if (t->value) {
                lv_label_set_text_fmt(t->value, "%d%%", (int)pct);
            }
        } else if (t->icon) {
            lv_obj_set_style_text_color(t->icon,
                                        lv_color_hex((seq % 2) ? S2_COL_WARN : S2_COL_TEXT_LO),
                                        LV_PART_MAIN);
        }
        break;

    case S2_COVER:
        if (t->bar) {
            lv_bar_set_value(t->bar, (int32_t)(seq * 3 % 101), LV_ANIM_OFF);
        }
        break;

    default:
        /* Scenes are stateless (§7.4) and the placeholder has nothing to show.
         * Both are left alone deliberately: a real page has tiles that never
         * update, and counting them as updated would overstate the load. */
        break;
    }
}

uint32_t s2_scene_tile_count(void)
{
    return s_tile_count;
}
