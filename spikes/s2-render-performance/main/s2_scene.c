/*
 * Spike S-2 — the scene being rendered.
 *
 * Adapted from the S-1 harness (PR #46, commit 04e6149), which built the same
 * §7 components for a heap measurement. Three things are different here, and
 * each of them is a render cost S-1 could not see:
 *
 *   1. Real fonts. S-1 used built-in Montserrat and said so; the §8 type scale
 *      and the two §7.1 icon sizes are bpp:4 faces whose glyph cache is a
 *      render-time cost. This is where that shows up.
 *   2. Tiles keep handles to the widgets that change, because §5.2 delivers
 *      state diffs and the runtime updates a label rather than rebuilding a
 *      tile. Measuring a rebuild per update would measure the wrong thing.
 *   3. Animations run continuously on four tiles, per the issue's scope.
 */

